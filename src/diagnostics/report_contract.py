"""Договор об отчёте BlockCheck: какие поля в нём есть и где каждое показано.

Отчёт — единственный источник истины: его собирает движок
(``diagnostics.engine``), по нему рисуется экран, он же целиком пишется в файл.
Экран не может показать то, чего в отчёте нет. Обратное само не получается:
новое поле можно положить в отчёт и забыть вывести. Этот список закрывает
такую дыру — у каждого поля отчёта здесь должно быть одно из трёх мест:

- ``CARD_FIELDS`` — поле видно на карточках результатов;
- ``SUMMARY_FIELDS`` — поле читает панель итога или сама страница;
- ``SERVICE_FIELDS`` — поле служебное, с объяснением, почему его не показывают.

Тесты (``tests/test_report_contract.py``) проверяют обе стороны: что в отчёте
движка нет поля мимо списка и что каждое показываемое поле действительно меняет
экран. Список намеренно только про верхний уровень отчёта: внутри раздела поля
читает одна функция карточки, и расхождение там видно в её собственных тестах.
"""

from __future__ import annotations

__all__ = ["CARD_FIELDS", "SERVICE_FIELDS", "SUMMARY_FIELDS", "declared_fields"]

# Разделы, из которых строятся карточки результатов.
CARD_FIELDS: tuple[str, ...] = (
    "services",
    "freeze",
    "voice",
    "telegram",
    "network",
    "speed",
    "ipv6",
    "dns_servers",
    "filter",
    "habits",
    # Карточка «Несколько соединений сразу».
    "crowd",
    "system",
    "registry",
    "reference",
    "spoofed_hosts",
    # Карточка «Ход проверки»: время шагов и условия, при которых шла проверка.
    "step_seconds",
    "environment",
    "zapret_line",
    "other_bypass_tools",
    # Какие из них стояли на дороге проверки (VPN с проложенной дорогой, программы, меняющие пакеты).
    "tools_in_path",
    "preset",
    # Карточка «С Zapret и без»: сравнение с прошлой проверкой в противоположном состоянии обхода.
    "compare",
)

# Поля, которые читает панель итога и страница.
SUMMARY_FIELDS: tuple[str, ...] = (
    "scope",
    "problems",
    "working",
    "zapret_running",
    "elapsed",
    "timed_out",
    "history",
    "text",
)

# Служебные поля: на экран не выводятся, и вот почему.
SERVICE_FIELDS: dict[str, str] = {
    "partial": "признак «отчёт ещё пополняется»: по нему экран отличает ход проверки от итога",
    "dns_poisoning_detected": "то же, что непустой spoofed_hosts; оставлено для записи истории",
    "changes": "что изменилось с прошлой проверки — уходит в «Прошлые проверки» через запись истории",
    "previous_time": "время прошлой такой же проверки — нужно только для строки об изменениях",
    "json_file": "путь к файлу отчёта — по нему собирается обращение в поддержку",
    "stopped": "пометка прерванной проверки в сохранённом файле",
    "failed": "пометка упавшей проверки в сохранённом файле",
    "error": "текст ошибки упавшей проверки",
}


def declared_fields() -> frozenset[str]:
    """Все поля, которым в отчёте есть место."""
    return frozenset(CARD_FIELDS) | frozenset(SUMMARY_FIELDS) | frozenset(SERVICE_FIELDS)
