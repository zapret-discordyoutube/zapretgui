def hostlist_help(*, exceptions: bool = True) -> HelpContent:
    """Справка о списке сайтов. ``exceptions=False`` — режим Zapret 1: winws не понимает «!»."""
    zapret1_note = (
        ""
        if exceptions
        else "\n\nВ режиме Zapret 1 «!» не работает: старый движок winws его не понимает и примет "
        "«!сайт» за имя сайта. «^» работает в обоих режимах."
    )
    return HelpContent(
        "Список сайтов",
        "Здесь два поля. «Ваши записи» — то, что вы добавили сами; они хранятся отдельно и не пропадают при "
        "обновлении. «Встроенные записи» приходят с программой. Движок получает один файл: сначала ваши "
        "записи, потом встроенные.\n\n"
        "Одна строка — один домен:\n"
        "• example.com — сам домен и все его поддомены: www.example.com, cdn.example.com.\n"
        "• ^example.com — только сам домен, без поддоменов.\n"
        "• !example.com — исключение: домен и его поддомены не считаются частью этого списка. Пример: "
        "«ru» и «!torrents.ru» — все сайты .ru, кроме torrents.ru.\n"
        "• Префиксы сочетаются: «!^a.ru» исключает только сам a.ru, а www.a.ru остаётся в списке.\n"
        "• Строки с # в начале — комментарии. Звёздочки не нужны и не работают: поддомены учитываются сами.\n\n"
        "Что важнее чего:\n"
        "• Движок ищет сайт от точного имени к общему: www.torrents.ru → torrents.ru → ru. Решает первая "
        "найденная запись, поэтому «!torrents.ru» сильнее «ru», где бы они ни стояли.\n"
        "• Один домен учитывается один раз — по первой записи. Ваши записи стоят первыми, поэтому ваше "
        "«!youtube.com» отключает встроенное «youtube.com».\n"
        "• «!» действует только внутри этого файла. Если тот же сайт есть в другом списке этого профиля, "
        "профиль его всё равно возьмёт.\n"
        "• Если это список исключений (--hostlist-exclude), «!» значит «не исключать».\n"
        "• В автосписке (--hostlist-auto) «!домен» исключает домен из всего профиля."
        + zapret1_note,
        (LINK_HOSTLIST, LINK_EXCLUSIONS, LINK_FILTER, LINK_PROFILE),
    )


