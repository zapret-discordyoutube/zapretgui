from __future__ import annotations

import threading

# Папки пресетов и папки профилей лежат в одной секции настроек «folders» и
# сохраняются целиком: чтение -> правка своей части -> запись всей секции.
# Под разными замками запись одной стороны могла откатить параллельную правку
# другой, поэтому read-modify-write обеих сторон идёт под этим одним замком.
FOLDERS_SETTINGS_LOCK = threading.RLock()
