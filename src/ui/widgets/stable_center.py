"""Центр прямоугольника, который не «прыгает» у верхнего края списка.

QRect.center() считает на C++ целочисленным делением, которое округляет к нулю.
Для прямоугольника с неотрицательными координатами это то же, что деление с
округлением вниз, но у плитки, которая наполовину ушла выше верхнего края списка
(отрицательный верх), центр выходит на точку ниже. Значок и имя такой плитки
рисовались на пиксель ниже, чем когда плитка видна целиком, и при прокрутке
сдвигались на пиксель в момент, когда её верх пересекал край.

Здесь центр считается от верхнего левого угла и не зависит от знака координат,
поэтому для всех видимых целиком плиток результат тот же, что у center().
"""

from __future__ import annotations

from PyQt6.QtCore import QPoint, QRect


def center_x(rect: QRect) -> int:
    return rect.left() + (rect.width() - 1) // 2


def center_y(rect: QRect) -> int:
    return rect.top() + (rect.height() - 1) // 2


def center_point(rect: QRect) -> QPoint:
    return QPoint(center_x(rect), center_y(rect))
