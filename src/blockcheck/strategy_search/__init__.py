"""Подбор стратегии обхода DPI.

Как устроено (от начала к концу):

1. ``engine`` — порядок работы подбора: подготовка, проверка «до подбора»,
   цикл по стратегиям, перепроверка победителей, возврат в исходное состояние.
2. ``probes`` — сами сетевые проверки (HTTPS, STUN, игровые UDP-запросы) на
   заранее выбранных адресах.
3. ``verdict`` — правила: что считать «открылось», «заблокировано», «сеть
   пропала». Только чистые функции, без сети и процессов.
4. ``winws_session`` — запуск одной стратегии в winws2 и её остановка.
5. ``probe_profile`` — строки профиля, которые проверяются и потом ровно так же
   записываются в пресет кнопкой «Применить».
6. ``ordering`` и ``history`` — в каком порядке проверять стратегии и что
   запомнить о прошлых подборах.
"""
