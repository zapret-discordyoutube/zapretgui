"""Установка обновления: передача установщику, наблюдатель и восстановление.

Здесь нет Qt: модули работают в фоновых задачах и при следующем запуске.

* ``paths`` — каталог состояния обновления вне каталога установки;
* ``handoff`` — запись о ходе установки, общая с наблюдателем;
* ``launcher`` — единственный путь запуска установщика;
* ``watchdog`` и ``watchdog_script`` — наблюдатель и его PowerShell-скрипт;
* ``recovery_hook`` — страховка ``RunOnce`` на случай выключения питания;
* ``interrupted`` — разбор сорвавшегося обновления при следующем запуске;
* ``repair`` — починка поставки тем же установщиком.
"""
